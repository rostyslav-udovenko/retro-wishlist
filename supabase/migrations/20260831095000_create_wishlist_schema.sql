-- Retro Wishlist initial database schema
-- Public clients access wishlist data and reservation mutations only through RPC functions.

create table public.wishlists (
  id bigint generated by default as identity primary key,
  slug text not null,
  title text not null,
  owner_name text not null,
  description text not null default '',
  icon text not null default '🎁',
  visibility text not null default 'public',
  is_featured boolean not null default false,
  is_active boolean not null default true,
  display_order integer not null default 100,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint wishlists_slug_unique unique (slug),
  constraint wishlists_slug_format check (
    slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'
    and char_length(slug) between 3 and 80
  ),
  constraint wishlists_title_length check (char_length(title) between 1 and 120),
  constraint wishlists_owner_name_length check (
    char_length(owner_name) between 1 and 100
  ),
  constraint wishlists_description_length check (
    char_length(description) <= 1000
  ),
  constraint wishlists_icon_length check (char_length(icon) between 1 and 32),
  constraint wishlists_visibility_valid check (
    visibility in ('public', 'unlisted')
  ),
  constraint wishlists_display_order_valid check (display_order >= 0)
);

create table public.gifts (
  id bigint generated by default as identity primary key,
  wishlist_id bigint not null references public.wishlists(id) on delete cascade,
  gift_key text not null,
  name text not null,
  description text not null default '',
  price text not null default '',
  image text not null default '🎁',
  store_url text,
  accent text not null default 'blue',
  display_order integer not null default 100,
  is_visible boolean not null default true,
  reserved_by text,
  reservation_token uuid,
  reserved_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint gifts_wishlist_key_unique unique (wishlist_id, gift_key),
  constraint gifts_key_format check (
    gift_key ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'
    and char_length(gift_key) between 2 and 100
  ),
  constraint gifts_name_length check (char_length(name) between 1 and 160),
  constraint gifts_description_length check (char_length(description) <= 2000),
  constraint gifts_price_length check (char_length(price) <= 120),
  constraint gifts_image_length check (char_length(image) between 1 and 2048),
  constraint gifts_store_url_length check (
    store_url is null or char_length(store_url) <= 2048
  ),
  constraint gifts_store_url_protocol check (
    store_url is null or store_url ~ '^https://'
  ),
  constraint gifts_accent_valid check (accent in ('blue', 'pink', 'yellow')),
  constraint gifts_display_order_valid check (display_order >= 0),
  constraint gifts_reserved_by_length check (
    reserved_by is null or char_length(reserved_by) between 2 and 50
  ),
  constraint gifts_reservation_state_consistent check (
    (
      reserved_by is null
      and reservation_token is null
      and reserved_at is null
    )
    or
    (
      reserved_by is not null
      and reservation_token is not null
      and reserved_at is not null
    )
  )
);

create index wishlists_directory_idx
  on public.wishlists (display_order, id)
  where is_active = true and visibility = 'public' and is_featured = true;

create index gifts_wishlist_display_idx
  on public.gifts (wishlist_id, display_order, id)
  where is_visible = true;

create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger wishlists_set_updated_at
before update on public.wishlists
for each row
execute function public.set_updated_at();

create trigger gifts_set_updated_at
before update on public.gifts
for each row
execute function public.set_updated_at();

