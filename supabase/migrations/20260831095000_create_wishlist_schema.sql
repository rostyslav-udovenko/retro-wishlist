create or replace function public.get_featured_wishlists()
returns table (
  slug text,
  title text,
  owner_name text,
  description text,
  icon text,
  total_gifts bigint,
  available_gifts bigint
)
language sql
stable
security definer
set search_path = ''
as $$
  select
    w.slug,
    w.title,
    w.owner_name,
    w.description,
    w.icon,
    count(g.id) as total_gifts,
    count(g.id) filter (where g.reserved_at is null) as available_gifts
  from public.wishlists as w
  left join public.gifts as g
    on g.wishlist_id = w.id
   and g.is_visible = true
  where w.is_active = true
    and w.visibility = 'public'
    and w.is_featured = true
  group by
    w.id,
    w.slug,
    w.title,
    w.owner_name,
    w.description,
    w.icon,
    w.display_order
  order by w.display_order, w.id;
$$;

create or replace function public.get_wishlist(p_wishlist_slug text)
returns table (
  slug text,
  title text,
  owner_name text,
  description text,
  icon text,
  visibility text
)
language sql
stable
security definer
set search_path = ''
as $$
  select
    w.slug,
    w.title,
    w.owner_name,
    w.description,
    w.icon,
    w.visibility
  from public.wishlists as w
  where w.slug = lower(trim(p_wishlist_slug))
    and w.is_active = true
  limit 1;
$$;

create or replace function public.get_wishlist_gifts(p_wishlist_slug text)
returns table (
  id bigint,
  gift_key text,
  name text,
  description text,
  price text,
  image text,
  store_url text,
  accent text,
  display_order integer,
  is_reserved boolean
)
language sql
stable
security definer
set search_path = ''
as $$
  select
    g.id,
    g.gift_key,
    g.name,
    g.description,
    g.price,
    g.image,
    g.store_url,
    g.accent,
    g.display_order,
    g.reserved_at is not null as is_reserved
  from public.gifts as g
  join public.wishlists as w on w.id = g.wishlist_id
  where w.slug = lower(trim(p_wishlist_slug))
    and w.is_active = true
    and g.is_visible = true
  order by g.display_order, g.id;
$$;

create or replace function public.reserve_gift(
  p_wishlist_slug text,
  p_gift_id bigint,
  p_guest_name text,
  p_visitor_token uuid
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_guest_name text := regexp_replace(trim(p_guest_name), '\s+', ' ', 'g');
  v_updated_id bigint;
begin
  if char_length(v_guest_name) not between 2 and 50 then
    raise exception using
      errcode = '22023',
      message = 'Guest name must contain between 2 and 50 characters.';
  end if;

  if p_visitor_token is null then
    raise exception using
      errcode = '22023',
      message = 'Visitor token is required.';
  end if;

  update public.gifts as g
  set
    reserved_by = v_guest_name,
    reservation_token = p_visitor_token,
    reserved_at = now()
  from public.wishlists as w
  where g.id = p_gift_id
    and g.wishlist_id = w.id
    and w.slug = lower(trim(p_wishlist_slug))
    and w.is_active = true
    and g.is_visible = true
    and g.reserved_at is null
  returning g.id into v_updated_id;

  return v_updated_id is not null;
end;
$$;

create or replace function public.release_gift(
  p_wishlist_slug text,
  p_gift_id bigint,
  p_visitor_token uuid
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_updated_id bigint;
begin
  if p_visitor_token is null then
    raise exception using
      errcode = '22023',
      message = 'Visitor token is required.';
  end if;

  update public.gifts as g
  set
    reserved_by = null,
    reservation_token = null,
    reserved_at = null
  from public.wishlists as w
  where g.id = p_gift_id
    and g.wishlist_id = w.id
    and w.slug = lower(trim(p_wishlist_slug))
    and w.is_active = true
    and g.is_visible = true
    and g.reservation_token = p_visitor_token
    and g.reserved_at is not null
  returning g.id into v_updated_id;

  return v_updated_id is not null;
end;
$$;

